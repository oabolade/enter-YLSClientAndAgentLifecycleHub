import type { Client, Policy } from "./types";
import { LINE_NAME_EN } from "./labels";

const escapePdf = (text: string) =>
  text.replace(/[^\x20-\x7E]/g, "?").replace(/[\\()]/g, "\\$&");

/** Builds a one-page PDF from plain text lines (ASCII only). */
function buildPdf(lines: string[]): Blob {
  const content = [
    "BT",
    "/F1 12 Tf",
    "72 720 Td",
    "18 TL",
    ...lines.map((line) => `(${escapePdf(line)}) Tj T*`),
    "ET",
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefStart = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((offset) => `${String(offset).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;
  return new Blob([pdf], { type: "application/pdf" });
}

/** Downloads a clearly marked sample document; no real carrier files exist yet. */
export function downloadSampleDocument(client: Client, policy: Policy, documentName: string) {
  const blob = buildPdf([
    "SAMPLE DOCUMENT - NOT A VALID INSURANCE DOCUMENT",
    "",
    "YLS Financial & Insurance Services",
    `Document: ${documentName}`,
    "",
    `Insured: ${client.fullName}`,
    `Policy number: ${policy.policyNumber}`,
    `Line: ${LINE_NAME_EN[policy.line]}`,
    `Carrier: ${policy.carrier}`,
    `Renewal date: ${policy.renewalDate}`,
    `Deductible: ${policy.deductible}`,
    "",
    "Generated by the YLS 360 Client & Agent Hub demo.",
  ]);
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `SAMPLE_${documentName}`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
